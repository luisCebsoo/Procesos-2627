async function seed() {
  const uri = process.env.MONGODB_URI;
  if (!uri) {
    console.error("No se encontró MONGODB_URI en el archivo .env");
    process.exit(1);
  }

  const client = new MongoClient(uri);
  try {
    await client.connect();
    const db = client.db();
    const coleccion = db.collection("catalogo");

    // Limpia y siembra los 18 cafés completos
    await coleccion.deleteMany({});
    await coleccion.insertMany(CATALOGO_COMPLETO);

    const total = await coleccion.countDocuments();
    console.log(JSON.stringify({
      t: new Date().toISOString(),
      level: "info",
      msg: "catálogo sembrado con éxito en MongoDB Atlas",
      totalCafes: total,
    }));
  } catch (err) {
    console.error("Error sembrando catálogo:", err.message);
    process.exit(1);
  } finally {
    await client.close();
  }
}

seed();
